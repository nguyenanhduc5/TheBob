export const supportedLocales = ['vi', 'zh', 'en'];
const localeStorageKey = 'thebob-locale';
const localeTags = { vi: 'vi-VN', en: 'en-US', zh: 'zh-CN' };

function getSavedLocale() {
  try {
    const savedLocale = window.localStorage.getItem(localeStorageKey);
    return supportedLocales.includes(savedLocale) ? savedLocale : 'vi';
  } catch {
    return 'vi';
  }
}

export function PreferencesProvider({ children }) {
  const [locale, setLocaleState] = useState(getSavedLocale);

  const setLocale = useCallback((nextLocale) => {
    if (supportedLocales.includes(nextLocale)) {
      setLocaleState(nextLocale);
    }
  }, []);

  useEffect(() => {
    try {
      window.localStorage.setItem(localeStorageKey, locale);
    } catch {
      // The preference still applies for this session when storage is unavailable.
    }
    document.documentElement.lang = localeTags[locale];
  }, [locale]);

  useEffect(() => {
    const syncLocale = (event) => {
      if (event.key === localeStorageKey && supportedLocales.includes(event.newValue)) {
        setLocaleState(event.newValue);
      }
    };
    window.addEventListener('storage', syncLocale);
    return () => window.removeEventListener('storage', syncLocale);
  }, []);

  useEffect(() => {
    try {
      window.localStorage.removeItem('thebob-theme');
    } catch {
      // Theme cleanup is optional when storage is unavailable.
    }
  }, []);

  const t = useCallback((key, values = {}) => {
    const message = messages[locale]?.[key] || messages.vi[key] || key;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      message
    );
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return (
    <PreferencesContext.Provider value={value}>
      {children}
    </PreferencesContext.Provider>
  );
}

export function usePreferences() {
  const context = useContext(PreferencesContext);
  if (!context) {
    throw new Error('usePreferences must be used within a PreferencesProvider');
  }
  return context;
}
